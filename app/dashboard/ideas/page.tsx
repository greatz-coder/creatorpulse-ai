'use client';

import { useState } from 'react';
import { Check, Copy, Loader2, Lightbulb, WandSparkles } from 'lucide-react';
import { Button, Card, Input, Select } from '@/components/ui';

type Tone = 'Energetic' | 'Controversial' | 'Educational' | 'Humorous';
type Idea = { title: string; format: string; structure: string };

export default function IdeaLabPage() {
  const [niche, setNiche] = useState('');
  const [audience, setAudience] = useState('');
  const [tone, setTone] = useState<Tone>('Educational');
  const [ideas, setIdeas] = useState<Idea[]>([]);
  const [mode, setMode] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState<number | null>(null);

  const generate = async (event: React.FormEvent) => {
    event.preventDefault(); setBusy(true); setError(''); setIdeas([]);
    try {
      const response = await fetch('/api/ideas', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ niche, audience, tone }) });
      const data = await response.json();
      if (!response.ok) throw new Error(data.error || 'Could not create ideas.');
      setIdeas(data.ideas); setMode(data.mode);
    } catch (err) { setError(err instanceof Error ? err.message : 'Request failed.'); }
    finally { setBusy(false); }
  };

  const copy = async (idea: Idea, index: number) => {
    try { await navigator.clipboard.writeText(`${idea.title}\n\nFormat: ${idea.format}\n\nStructure: ${idea.structure}`); setCopied(index); window.setTimeout(() => setCopied(null), 1500); }
    catch { setError('Clipboard is unavailable; select and copy the idea manually.'); }
  };

  return <div className="mx-auto max-w-4xl space-y-6">
    <header><p className="text-xs uppercase tracking-[0.28em] text-violet-200/75">Free Creator Tool</p><h1 className="mt-2 text-3xl font-bold">Idea Lab</h1><p className="mt-2 max-w-2xl text-sm leading-6 text-slate-400">Get five niche-aware video concepts with a suggested format and structure. Runs with local templates at no cost; configure the optional hosted model for more flexible ideas.</p></header>
    <Card className="border-slate-800 bg-slate-900/80 p-5 sm:p-6"><form onSubmit={generate} className="grid gap-4 sm:grid-cols-2">
      <label className="space-y-2 text-sm text-slate-300">Your niche<Input required maxLength={80} value={niche} onChange={(event) => setNiche(event.target.value)} placeholder="e.g. affordable skincare" /></label>
      <label className="space-y-2 text-sm text-slate-300">Who do you help?<Input required maxLength={100} value={audience} onChange={(event) => setAudience(event.target.value)} placeholder="e.g. students on a budget" /></label>
      <label className="space-y-2 text-sm text-slate-300 sm:col-span-2">Tone<Select value={tone} onChange={(event) => setTone(event.target.value as Tone)}><option>Energetic</option><option>Controversial</option><option>Educational</option><option>Humorous</option></Select></label>
      {error && <p role="alert" className="text-sm text-rose-300 sm:col-span-2">{error}</p>}
      <Button type="submit" disabled={busy} className="min-h-11 gap-2 sm:col-span-2">{busy ? <Loader2 className="h-4 w-4 animate-spin" /> : <WandSparkles className="h-4 w-4" />}{busy ? 'Creating ideas…' : 'Generate 5 ideas'}</Button>
    </form></Card>
    {ideas.length > 0 && <section className="space-y-3" aria-live="polite"><div><h2 className="text-xl font-semibold">Your ideas</h2><p className="mt-1 text-xs text-slate-500">{mode === 'hosted-llm' ? 'Generated by your configured hosted model' : 'Generated by local idea frameworks'}</p></div><div className="grid gap-3 md:grid-cols-2">{ideas.map((idea, index) => <Card key={`${idea.title}-${index}`} className="border-slate-800 bg-slate-900/80 p-5"><div className="flex items-start justify-between gap-3"><span className="flex h-9 w-9 shrink-0 items-center justify-center rounded-xl bg-violet-500/10 text-violet-200"><Lightbulb className="h-4 w-4" /></span><button type="button" onClick={() => void copy(idea, index)} className="inline-flex min-h-9 items-center gap-1 rounded-full border border-slate-700 px-3 text-xs hover:border-violet-400">{copied === index ? <Check className="h-3 w-3" /> : <Copy className="h-3 w-3" />}{copied === index ? 'Copied' : 'Copy'}</button></div><h3 className="mt-4 font-semibold leading-6">{idea.title}</h3><p className="mt-3 text-xs uppercase tracking-wider text-violet-200/80">{idea.format}</p><p className="mt-2 text-sm leading-6 text-slate-400">{idea.structure}</p></Card>)}</div></section>}
    <p className="text-xs leading-5 text-slate-500">Ideas are prompts to adapt to your own experience. No idea or script guarantees reach or growth.</p>
  </div>;
}
